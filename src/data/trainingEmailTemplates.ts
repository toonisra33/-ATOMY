/**
 * Format email template into plain text & HTML ready for sending or copying
 */
export function generateFormattedEmail(
  dayNumber: number,
  prospectName: string = "เพื่อนสมาชิกคนพิเศษ",
  sponsorName: string = "ทีมงานสปอนเซอร์ Atomy",
  sponsorLine: string = "",
  baseUrl: string = typeof window !== "undefined" ? window.location.origin : "",
  recipientEmail: string = ""
) {
  const template = TRAINING_EMAIL_TEMPLATES[dayNumber] || TRAINING_EMAIL_TEMPLATES[1];
  const trainingLink = `${baseUrl}/day${dayNumber}`;

  // Replace placeholders in text
  const cleanSubject = template.subject.replace(/{{PROSPECT_NAME}}/g, prospectName);
  const cleanIntro = template.storyIntro
    .replace(/{{PROSPECT_NAME}}/g, prospectName)
    .replace(/{{SPONSOR_NAME}}/g, sponsorName);

  const textBody = `
${template.badge}
หัวข้อ: ${template.headline}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

${cleanIntro}

🎯 สิ่งสำคัญที่คุณจะได้ค้นพบในบทเรียนนี้:
${template.coreLessons.map((l, i) => `  ${i + 1}. ${l}`).join("\n")}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
👉 คลิกเข้าเรียนที่นี่: ${trainingLink}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

${template.psNote}

${template.countdownNotice}

ด้วยความปรารถนาดีและพร้อมสนับสนุนความสำเร็จของคุณ,
${sponsorName}
${sponsorLine ? `ติดต่อพูดคุย: LINE ID ${sponsorLine}` : ""}
`.trim();

  const encodedSubject = encodeURIComponent(cleanSubject);
  const encodedBody = encodeURIComponent(textBody);
  const encodedTo = recipientEmail ? encodeURIComponent(recipientEmail) : "";

  return {
    template,
    subject: cleanSubject,
    preheader: template.preheader,
    textBody,
    trainingLink,
    mailtoUrl: `mailto:${recipientEmail}?subject=${encodedSubject}&body=${encodedBody}`,
    gmailWebUrl: `https://mail.google.com/mail/?view=cm&fs=1${encodedTo ? `&to=${encodedTo}` : ""}&su=${encodedSubject}&body=${encodedBody}`,
  };
}
